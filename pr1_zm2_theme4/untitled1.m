% =========================================================================
% ЧАСТИНА 1: ПОБУДОВА ЕТАЛОННОЇ ПОВЕРХНІ
% =========================================================================
clear all; close all; clc;

disp('Частина 1: Побудова еталонної поверхні...');

% Параметри для побудови
n = 15;
x1_range = [-7 3];
x2_range = [-4.4 1.7];
x1_vec = linspace(x1_range(1), x1_range(2), n);
x2_vec = linspace(x2_range(1), x2_range(2), n);
[X1, X2] = meshgrid(x1_vec, x2_vec);
Y_target = X1.^2 .* sin(X2 - 1);

% Візуалізація
figure('Name', 'Еталонна поверхня', 'NumberTitle', 'off');
surf(X1, X2, Y_target);
xlabel('x1');
ylabel('x2');
zlabel('y');
title('Еталонна поверхня: y = x1^2 * sin(x2 - 1)');
colorbar;
disp('Еталонну поверхню побудовано.');
pause(1);